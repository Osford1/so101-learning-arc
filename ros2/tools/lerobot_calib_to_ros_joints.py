#!/usr/bin/env python3
"""
lerobot_calib_to_ros_joints.py — turn a LeRobot SO-101 calibration file into the
joint_config_file that feetech_ros2_driver (ros2_control) expects.

Why this is needed
------------------
The servos are the same hardware seen from two stacks:

  * LeRobot stores  {id, drive_mode, homing_offset, range_min, range_max} per motor in
    ~/.cache/huggingface/lerobot/calibration/robots/so101_follower/<arm_id>.json
    and reports joint positions in DEGREES, centred on the MIDPOINT of the calibrated
    travel range ("0°" = (range_min+range_max)/2).
  * The ROS 2 driver reads raw ticks and treats tick **2048** as joint angle 0, with
    `range_min`/`range_max` given in ticks, *after* the servo's EEPROM homing offset.

Because a normal LeRobot SO-101 calibration centres the mid pose on tick 2048, the
two conventions coincide and the tick limits transfer 1:1 — that is the case this
script assumes, and it says so out loud (it prints the midpoints it found).

It deliberately does NOT emit `homing_offset`: that parameter is written to the
servo EEPROM, and LeRobot already put a value there. Writing a second one silently
invalidates LeRobot's stored calibration. Pass --ticks-at-zero if (and only if) you
have measured that ROS zero and LeRobot zero differ, and read the warning.

Usage
-----
  # from the calibration JSON
  python3 lerobot_calib_to_ros_joints.py \
      --calib ~/.cache/huggingface/lerobot/calibration/robots/so101_follower/my_awesome_follower_arm.json \
      --out ../ws_src/so101_local/config/so101_follower_joints.yaml

  # auto-find the newest calibration file in the LeRobot cache
  python3 lerobot_calib_to_ros_joints.py --out .../so101_follower_joints.yaml

  # redefine where ROS calls zero (measured, per joint, in ticks):
  python3 lerobot_calib_to_ros_joints.py --calib c.json --out j.yaml \
      --ticks-at-zero shoulder_pan=2048,wrist_flex=2600
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

# LeRobot joint name -> servo id, and the ROS joint name it maps to.
# (The SO-ARM101 uses the same names on both sides; kept explicit so a mismatch is visible.)
JOINTS = [
    ("shoulder_pan", 1),
    ("shoulder_lift", 2),
    ("elbow_flex", 3),
    ("wrist_flex", 4),
    ("wrist_roll", 5),
    ("gripper", 6),
]

TICK_CENTRE = 2048
MAX_TICK = 4095


def find_calibration() -> Path:
    root = Path.home() / ".cache/huggingface/lerobot/calibration/robots/so101_follower"
    files = sorted(root.glob("*.json"), key=lambda p: p.stat().st_mtime, reverse=True)
    if not files:
        sys.exit(f"no calibration file found under {root} — pass --calib explicitly")
    return files[0]


def load_calibration(path: Path) -> dict:
    raw = json.loads(path.read_text())
    # LeRobot writes either {motor: {...}} directly, or nested under "calibration".
    if "calibration" in raw and isinstance(raw["calibration"], dict):
        raw = raw["calibration"]
    return raw


def parse_ticks_at_zero(spec: str | None) -> dict[str, int]:
    out: dict[str, int] = {}
    if not spec:
        return out
    for chunk in spec.split(","):
        chunk = chunk.strip()
        if not chunk:
            continue
        if "=" not in chunk:
            sys.exit(f"--ticks-at-zero: expected joint=tick, got {chunk!r}")
        name, val = chunk.split("=", 1)
        out[name.strip()] = int(val)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--calib", type=Path, help="LeRobot calibration JSON (default: newest in the cache)")
    ap.add_argument("--out", type=Path, required=True, help="joint_config_file to write")
    ap.add_argument(
        "--ticks-at-zero",
        default=None,
        help="joint=tick,... tick the servo reads when the arm is at the ROS/URDF zero pose "
        "(writes homing_offset = tick - 2048 to EEPROM — see the warning in the header)",
    )
    ap.add_argument("--p-coefficient", type=int, default=16)
    ap.add_argument("--d-coefficient", type=int, default=32)
    ap.add_argument("--acceleration", type=int, default=254)
    args = ap.parse_args()

    calib_path = args.calib or find_calibration()
    calib = load_calibration(calib_path)
    ticks_at_zero = parse_ticks_at_zero(args.ticks_at_zero)

    lines: list[str] = []
    lines.append(f"# GENERATED by lerobot_calib_to_ros_joints.py from {calib_path}")
    lines.append("# joint_config_file for feetech_ros2_driver/FeetechHardwareInterface.")
    lines.append("# range_min/range_max are raw servo ticks (post-EEPROM-homing-offset).")
    lines.append("")
    lines.append("joints:")

    problems: list[str] = []
    for name, sid in JOINTS:
        c = calib.get(name)
        if c is None:
            problems.append(f"{name}: missing from the calibration file")
            continue
        cal_id = int(c.get("id", -1))
        if cal_id != sid:
            problems.append(f"{name}: calibration says id={cal_id}, the SO-ARM101 map expects {sid}")
        rmin = int(c["range_min"])
        rmax = int(c["range_max"])
        mid = (rmin + rmax) / 2
        # The gripper is normalised 0..100 (open..closed), not degrees, so its range
        # midpoint has no meaning as a "zero" — only the five body joints are checked.
        if name != "gripper" and abs(mid - TICK_CENTRE) > 60:
            problems.append(
                f"{name}: travel-range midpoint is {mid:.0f} ticks, not ~{TICK_CENTRE} — "
                "LeRobot's degree zero and the ROS tick-2048 zero will disagree by "
                f"{(TICK_CENTRE - mid) * 360 / MAX_TICK:+.1f}°"
            )
        if not (0 <= rmin < rmax <= MAX_TICK):
            problems.append(f"{name}: range {rmin}..{rmax} is outside the 0..{MAX_TICK} tick window")

        lines.append(f"  {name}:")
        lines.append(f"    id: {sid}")
        if name in ticks_at_zero:
            lines.append(
                f"    homing_offset: {ticks_at_zero[name] - TICK_CENTRE}   # EEPROM WRITE: "
                f"{ticks_at_zero[name]} ticks read as ROS zero"
            )
        else:
            lines.append(
                f"    # homing_offset: {int(round(mid)) - TICK_CENTRE}   # EEPROM write — only if ROS zero must move"
            )
        lines.append(f"    range_min: {rmin}")
        lines.append(f"    range_max: {rmax}")
        lines.append(f"    p_coefficient: {args.p_coefficient}")
        lines.append("    i_coefficient: 0")
        lines.append(f"    d_coefficient: {args.d_coefficient}")
        lines.append("    return_delay_time: 0")
        lines.append(f"    acceleration: {args.acceleration}")
        if name == "gripper":
            lines.append("    max_torque_limit: 500")
            lines.append("    protection_current: 250")
            lines.append("    overload_torque: 25")
        lines.append("")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n")

    print(f"wrote {args.out}  (from {calib_path})")
    for name, sid in JOINTS:
        c = calib.get(name)
        if c:
            print(
                f"  id {sid} {name:<14} range {int(c['range_min']):>4}..{int(c['range_max']):<4} "
                f"mid {(int(c['range_min']) + int(c['range_max'])) / 2:>7.1f}  "
                f"drive_mode {int(c.get('drive_mode', 0))}  lerobot homing_offset {int(c.get('homing_offset', 0)):+6d}"
            )
    if problems:
        print("\nCHECKS THAT NEED A HUMAN EYE:")
        for p in problems:
            print("  ! " + p)
        print(
            "\nNote: drive_mode=1 means LeRobot flips the sign of that joint. The ROS driver has no\n"
            "equivalent flag — if a joint moves the wrong way in ROS, that is the flag to compensate\n"
            "for (URDF axis sign, or the joint's own convention), not a wiring problem."
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
